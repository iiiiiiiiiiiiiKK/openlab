"""Dockerfile and compose generation with a hard security baseline.

Generated Dockerfiles:
- run as a non-root user,
- never enable privileged mode,
- expose exactly one port,
- bind the app to 0.0.0.0 inside the container so the host port mapping works.

Generated compose files always declare CPU/memory/pids limits, drop all Linux
capabilities, mount no host paths, and mount no Docker socket.
"""

from __future__ import annotations

import re
from pathlib import Path

from engine.project_analyzer.planner import RunPlan

SECURITY_BASELINE = {
    "cap_drop": ["ALL"],
    "security_opt": ["no-new-privileges:true"],
    "read_only_root": False,
}

FORBIDDEN_MOUNTS = (
    "/var/run/docker.sock",
    "\\\\.\\pipe\\docker_engine",
    "C:\\",
    "/",
    "~",
)


class PolicyViolation(ValueError):
    """Raised when a generated or user-provided environment breaks policy."""


def container_name_for(project_name: str, service: str = "app") -> str:
    slug = re.sub(r"[^a-z0-9_-]+", "-", project_name.lower()).strip("-")[:40] or "project"
    suffix = "" if service in ("app", "web", "main") else f"-{service}"
    return f"openlab-{slug}{suffix}"


def network_name_for(project_name: str) -> str:
    slug = re.sub(r"[^a-z0-9_-]+", "-", project_name.lower()).strip("-")[:40] or "project"
    return f"openlab-net-{slug}"


def generate_dockerfile(plan: RunPlan) -> str:
    """Build a Dockerfile from the run plan (used only when the repo has none)."""
    install = (plan.install_command or "").strip()
    build = (plan.build_command or "").strip()
    start = (plan.start_command or "").strip()
    if not start:
        raise PolicyViolation("cannot generate a Dockerfile without a start command")

    lines: list[str] = [
        "# Generated by OPENLAB -- original sources stay untouched in ./source",
        f"# strategy: {plan.strategy} | project_type: {plan.project_type} | port: {plan.port}",
        f"FROM {plan.base_image}",
        "ENV PYTHONUNBUFFERED=1 \\",
        "    NODE_ENV=production \\",
        "    HOME=/home/openlab",
        "RUN useradd --create-home --uid 10001 --shell /bin/bash openlab",
        "WORKDIR /app",
    ]

    copy_install = ""
    if install:
        lines.append("COPY --chown=openlab:openlab . /app")
        copy_install = f"RUN {_chain(install)}"

    if plan.project_type == "python" and "requirements.txt" not in install and install:
        lines.append("COPY --chown=openlab:openlab requirements.txt /app/requirements.txt")
        lines.append("RUN pip install --no-cache-dir -r requirements.txt")

    if plan.project_type == "python":
        lines.extend(
            [
                "RUN apt-get update && apt-get install -y --no-install-recommends curl && rm -rf /var/lib/apt/lists/*",
            ]
        )
    else:
        lines.append("RUN (apt-get update && apt-get install -y --no-install-recommends curl && rm -rf /var/lib/apt/lists/*) || true")

    if not install:
        lines.append("COPY --chown=openlab:openlab . /app")

    if copy_install:
        lines.append(copy_install)
    if build:
        lines.append(f"RUN {_chain(build)}")

    lines.extend(
        [
            "RUN mkdir -p /app/.openlab && chown -R openlab:openlab /app",
            "USER openlab",
            f"EXPOSE {plan.port}",
            'HEALTHCHECK --interval=10s --timeout=5s --start-period=45s --retries=6 '
            f'CMD curl -fsS http://127.0.0.1:{plan.port}{plan.health_path or "/"} || exit 1',
            f'CMD ["/bin/sh", "-lc", "{_escape_json(start)}"]',
        ]
    )
    return "\n".join(lines) + "\n"


def _chain(command: str) -> str:
    """Quote a multi-part shell command for a Dockerfile RUN instruction."""
    return command.replace('"', '\\"')


def _escape_json(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def generate_compose(
    plan: RunPlan,
    project_dir: Path,
    image_tag: str,
    host_port: int,
    cpu_limit: float = 2.0,
    memory_limit_mb: int = 4096,
    pids_limit: int = 512,
    allow_network: bool = False,
    dockerfile: str = "Dockerfile",
    extra_services: list[dict] | None = None,
) -> str:
    """Render a compose file with resource limits and no host mounts."""
    name = container_name_for(plan.project_name)
    net = network_name_for(plan.project_name)
    env_lines = [f"      - {var['name']}=${{{var['name']}:-}}" for var in plan.env_vars if var.get("name")]
    env_block = "\n".join(["    environment:"] + env_lines) if env_lines else ""

    services: list[str] = []
    app_service = [
        "  app:",
        f"    build:",
        f"      context: ..",
        f"      dockerfile: docker/{dockerfile}",
        f"    image: {image_tag}",
        f"    container_name: {name}",
        "    restart: \"no\"",
        "    ports:",
        f"      - \"127.0.0.1:{host_port}:{plan.port}\"",
    ]
    if env_block:
        app_service.append(env_block)
    app_service.extend(
        [
            "    deploy:",
            "      resources:",
            "        limits:",
            f"          cpus: \"{cpu_limit}\"",
            f"          memory: {memory_limit_mb}M",
            "        reservations:",
            "          cpus: \"0.25\"",
            f"          memory: {min(512, memory_limit_mb // 4)}M",
            f"    pids_limit: {pids_limit}",
            "    security_opt:",
            "      - no-new-privileges:true",
            "    cap_drop:",
            "      - ALL",
            "    privileged: false",
            "    read_only: false",
            "    tmpfs:",
            "      - /tmp:size=256M",
            f"    networks:",
            f"      - {net}",
        ]
    )
    if not allow_network:
        app_service.append("    # network access limited by default: OPENLAB_ALLOW_CONTAINER_NETWORK=false")
    services.append("\n".join(app_service))

    for service in extra_services or []:
        svc = [
            f"  {service['name']}:",
            f"    image: {service['image']}",
            f"    container_name: {container_name_for(plan.project_name, service['name'])}",
            "    restart: \"no\"",
            "    deploy:",
            "      resources:",
            "        limits:",
            "          cpus: \"1\"",
            "          memory: 512M",
            "    security_opt:",
            "      - no-new-privileges:true",
            "    networks:",
            f"      - {net}",
        ]
        services.append("\n".join(svc))

    body = "\n".join(services)
    return (
        "# Generated by OPENLAB -- resources are capped, no host mounts, no docker socket\n"
        f"name: {net}\n"
        "services:\n"
        f"{body}\n"
        "networks:\n"
        f"  {net}:\n"
        "    driver: bridge\n"
    )


def guard_compose_text(text: str) -> list[str]:
    """Return policy violations found in a compose file (empty when clean)."""
    lowered = (text or "").lower()
    problems: list[str] = []
    if "privileged: true" in lowered or "privileged:true" in lowered:
        problems.append("privileged containers are not allowed")
    if "docker.sock" in lowered:
        problems.append("Docker socket mounting is not allowed")
    for mount in ("/var/run", "/etc/", "/root", "c:\\users"):
        if re.search(rf"-\s*[\"']?{re.escape(mount)}", lowered):
            problems.append(f"host mount of {mount} is not allowed")
    if re.search(r"network_mode:\s*[\"']?host", lowered):
        problems.append("network_mode: host is not allowed")
    if "pid: host" in lowered or "ipc: host" in lowered:
        problems.append("sharing host PID/IPC namespaces is not allowed")
    return problems


def write_compose(project_dir: Path, filename: str, content: str) -> Path:
    docker_dir = Path(project_dir) / "docker"
    docker_dir.mkdir(parents=True, exist_ok=True)
    path = docker_dir / filename
    path.write_text(content, encoding="utf-8")
    return path


def discover_existing_compose(source_dir: Path) -> Path | None:
    for name in ("docker-compose.yml", "docker-compose.yaml", "compose.yml", "compose.yaml"):
        candidate = Path(source_dir) / name
        if candidate.exists():
            return candidate
    return None


def discover_existing_dockerfile(source_dir: Path) -> Path | None:
    for name in ("Dockerfile", "dockerfile", "Dockerfile.dev"):
        candidate = Path(source_dir) / name
        if candidate.exists():
            return candidate
    return None


SERVICE_IMAGES = {
    "postgres": "postgres:16-alpine",
    "mysql": "mysql:8",
    "mariadb": "mariadb:11",
    "redis": "redis:7-alpine",
    "mongodb": "mongo:7",
    "rabbitmq": "rabbitmq:3-management-alpine",
    "minio": "minio/minio:latest",
    "elasticsearch": "docker.elastic.co/elasticsearch/elasticsearch:8.13.0",
}


def required_service_containers(plan: RunPlan) -> list[dict]:
    out: list[dict] = []
    for service in plan.services:
        image = SERVICE_IMAGES.get(service.name)
        if image:
            out.append({"name": service.name, "image": image, "port": service.port})
    return out
